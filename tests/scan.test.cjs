'use strict';
/**
 * Zero-dependency tests:  node tests/scan.test.cjs   (or: npm test)
 *
 * Secret-shaped fixtures (bot tokens) are assembled at runtime from fragments so
 * that GitHub push protection and secret scanners never see a real-looking
 * credential in this repository.
 */
const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const SKILL = path.join(ROOT, 'skills', 'telegram-miniapp-security-audit');
const SCAN = path.join(SKILL, 'scripts', 'scan.cjs');
const { scan, toSarif, redact } = require(SCAN);
const RULES = require(path.join(SKILL, 'scripts', 'rules.cjs'));
const { helpers } = RULES;
const { validate } = require(path.join(SKILL, 'scripts', 'validate-findings.cjs'));

let passed = 0;
let failed = 0;
function test(name, fn) {
  try { fn(); passed++; console.log(`  ok   ${name}`); }
  catch (e) { failed++; console.log(`  FAIL ${name}\n       ${e.message}`); }
}

function copyDir(src, dst) {
  fs.mkdirSync(dst, { recursive: true });
  for (const e of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, e.name);
    const d = path.join(dst, e.name);
    if (e.isDirectory()) copyDir(s, d); else fs.copyFileSync(s, d);
  }
}

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'tma-test-'));
const vulnDir = path.join(tmp, 'vuln_app');
copyDir(path.join(__dirname, 'fixtures', 'vuln_app'), vulnDir);
const fakeTail = 'x'.repeat(33).replace(/x/g, (_, i) => 'FAKE0'[i % 5]);
const fakeToken = `1234567890:${'A' + 'A'}${fakeTail}`;
fs.writeFileSync(path.join(vulnDir, 'server', 'config.js'),
  `// generated by tests/scan.test.cjs: fake value only\nmodule.exports = { botToken: '${fakeToken}' };\n`);

console.log('\ntelegram-miniapp-security-audit tests\n');

const vuln = scan(vulnDir);
const hits = new Set(vuln.leads.map((l) => l.rule));

test('every rule fires on the vulnerable fixture', () => {
  const missing = RULES.map((r) => r.id).filter((id) => !hits.has(id));
  assert.deepStrictEqual(missing, [], `rules with no positive fixture: ${missing.join(', ')}`);
});

test('clean fixture produces zero leads', () => {
  const clean = scan(path.join(__dirname, 'fixtures', 'clean_app'));
  assert.strictEqual(clean.leads.length, 0, JSON.stringify(clean.leads.map((l) => `${l.rule} ${l.file}:${l.line}`)));
});

test('rule ids are unique and well-formed', () => {
  const ids = RULES.map((r) => r.id);
  assert.strictEqual(new Set(ids).size, ids.length, 'duplicate rule id');
  for (const r of RULES) {
    assert.match(r.id, /^TMA-[A-Z]{2,4}-\d{3}$/);
    assert.ok(['critical', 'high', 'medium', 'low', 'info'].includes(r.severity), `${r.id} severity`);
    assert.match(r.cwe, /^CWE-\d+$/, `${r.id} cwe`);
    assert.ok(r.pattern.flags.includes('g'), `${r.id} pattern needs the g flag`);
    for (const k of ['title', 'message', 'fix']) assert.ok(r[k] && r[k].length > 10, `${r.id} ${k}`);
  }
});

test('every rule guide anchor exists in its checks file', () => {
  const slug = (h) => h.toLowerCase().replace(/[^\w\s-]/g, '').trim().replace(/\s+/g, '-');
  for (const r of RULES) {
    const [file, anchor] = r.guide.split('#');
    const md = fs.readFileSync(path.join(SKILL, 'checks', file), 'utf8');
    const anchors = md.split('\n').filter((l) => /^#{1,4} /.test(l)).map((l) => slug(l.replace(/^#+ /, '')));
    assert.ok(anchors.includes(anchor), `${r.id}: ${r.guide} not found (have: ${anchors.join(', ')})`);
  }
});

test('bot tokens are redacted in snippets and JSON output', () => {
  const lead = vuln.leads.find((l) => l.rule === 'TMA-SEC-001');
  assert.ok(lead, 'TMA-SEC-001 lead missing');
  assert.ok(!lead.snippet.includes(fakeTail), 'token tail must not appear in the snippet');
  assert.ok(lead.snippet.includes('1234567890:AA…'));
  assert.ok(!JSON.stringify(vuln).includes(fakeTail), 'token tail leaked into the JSON result');
  assert.strictEqual(redact(`x='${fakeToken}'`), "x='1234567890:AA…'");
});

test('file-level rules report once per file', () => {
  for (const id of ['TMA-AUTH-003', 'TMA-AUTH-004', 'TMA-NET-001']) {
    const files = vuln.leads.filter((l) => l.rule === id).map((l) => l.file);
    assert.strictEqual(files.length, new Set(files).size, `${id} reported twice in one file`);
  }
});

test('frontend/server split puts each rule on the right side', () => {
  assert.ok(helpers.isFrontend('webapp/src/main.js'));
  assert.ok(helpers.isFrontend('miniapp/components/Pay.vue'));
  assert.ok(!helpers.isFrontend('server/index.js'));
  assert.ok(!helpers.isFrontend('src/api/routes.ts'));
  assert.ok(helpers.isServer('bot/handlers/start.py'));
  assert.ok(helpers.isServer('src/server.ts'));
  assert.ok(vuln.leads.filter((l) => l.rule === 'TMA-AUTH-002').every((l) => l.file.startsWith('server/')));
  assert.ok(vuln.leads.filter((l) => l.rule === 'TMA-PAY-001').every((l) => l.file.startsWith('webapp/')));
});

test('tma-ignore suppresses a reviewed line', () => {
  const dir = path.join(tmp, 'ignore_app', 'src');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'a.js'), "el.innerHTML = trustedSvg; // tma-ignore: TMA-WEB-001 static icon\nother.innerHTML = x;\n");
  const r = scan(path.dirname(dir));
  assert.strictEqual(r.leads.filter((l) => l.rule === 'TMA-WEB-001').length, 1);
});

test('test files and node_modules are skipped by default', () => {
  const dir = path.join(tmp, 'skip_app');
  for (const rel of ['src/__tests__/a.js', 'node_modules/pkg/src/b.js', 'src/c.spec.ts']) {
    fs.mkdirSync(path.join(dir, path.dirname(rel)), { recursive: true });
    fs.writeFileSync(path.join(dir, rel), 'el.innerHTML = x;\n');
  }
  assert.strictEqual(scan(dir).leads.length, 0);
  assert.ok(scan(dir, { includeTests: true }).leads.length >= 2);
});

test('SARIF output is well-formed', () => {
  const sarif = toSarif(vuln);
  assert.strictEqual(sarif.version, '2.1.0');
  const run = sarif.runs[0];
  assert.strictEqual(run.results.length, vuln.leads.length);
  const ruleIds = new Set(run.tool.driver.rules.map((r) => r.id));
  assert.ok(run.results.every((r) => ruleIds.has(r.ruleId) && r.locations[0].physicalLocation.region.startLine > 0));
  assert.ok(!JSON.stringify(sarif).includes(fakeTail));
});

test('CLI --fail-on exits 1 on the vulnerable fixture and 0 on the clean one', () => {
  let code = 0;
  try { execFileSync('node', [SCAN, vulnDir, '--fail-on', 'high', '--quiet']); } catch (e) { code = e.status; }
  assert.strictEqual(code, 1);
  execFileSync('node', [SCAN, path.join(__dirname, 'fixtures', 'clean_app'), '--fail-on', 'info', '--quiet']);
});

test('CLI --out and --sarif write valid JSON', () => {
  const out = path.join(tmp, 'out', 'leads.json');
  const sarif = path.join(tmp, 'out', 'leads.sarif');
  execFileSync('node', [SCAN, vulnDir, '--out', out, '--sarif', sarif, '--quiet']);
  assert.ok(JSON.parse(fs.readFileSync(out, 'utf8')).leads.length > 0);
  assert.strictEqual(JSON.parse(fs.readFileSync(sarif, 'utf8')).version, '2.1.0');
});

test('findings validator accepts the example and rejects a broken record', () => {
  const example = JSON.parse(fs.readFileSync(path.join(SKILL, 'templates', 'findings.example.json'), 'utf8'));
  assert.deepStrictEqual(validate(example), []);
  const broken = { target: 'x', findings: [{ id: 'F-1', verdict: 'confirmed', title: 't', location: { file: 'a' } }] };
  assert.ok(validate(broken).length >= 4);
  const nv = { target: 'x', findings: [{ id: 'F-1', verdict: 'needs_validation', title: 't', severity: 'high', location: { file: 'a' } }] };
  assert.ok(validate(nv).some((e) => e.includes('must NOT have a severity')));
});

test('reference initData validator passes its self-test', () => {
  const out = execFileSync('node', [path.join(SKILL, 'scripts', 'verify-init-data.cjs'), '--self-test']).toString();
  assert.match(out, /self-test passed/);
});

fs.rmSync(tmp, { recursive: true, force: true });
console.log(`\n${passed} passed, ${failed} failed\n`);
process.exit(failed ? 1 : 0);
